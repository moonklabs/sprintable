// 실시간 글자 수 카운터는 서버 Python `len()`과 같은 단위여야 한다. `str.length`(JS)는
// UTF-16 코드 유닛 수라 서프로게이트 페어로 인코딩되는 문자(대부분의 이모지)에서 서버
// 카운트와 어긋난다 — 실측: "😀"는 `.length`=2(서프로게이트 페어)인데 Python `len()`=1
// (코드포인트 1개). `[...text]`(스프레드)는 문자열을 코드포인트 단위로 순회하므로
// `[...text].length`가 Python `len()`과 정확히 같은 수를 낸다(ZWJ 결합 이모지처럼 여러
// 코드포인트로 이뤄진 것도 양쪽 다 각 코드포인트를 따로 센다 — 그래프임 클러스터 단위가
// 아니다, 그래서 사람 눈엔 "한 글자"로 보이는 이모지도 여러로 셀 수 있다 — 서버와 화면이
// 같은 숫자를 내는 것이 목적이지 "사람이 보는 글자 수"를 완벽히 맞추는 것이 목적이 아니다).
export function channelTextLength(text: string): number {
  return [...text].length;
}
